Q = "_quant_export_handler_QuantizeLinear_output_0"

def load_layers():
    z = np.load(ART / "fsr4_quality_weights.npz")
    spec = json.loads((ART / "graph_spec.json").read_text())
    L = {}
    for k in z.files:
        L[k] = z[k]
    # weight scales from decls (embedded) and bin scale table
    decl_scale = {dn.replace("post.", ""): d["scale"] for dn, d in spec["decls"].items() if d.get("scale")}
    for name in list(L.keys()):
        if name.startswith("embedded__") or name.startswith("embedded_hwcn__") or name.startswith("_"):
            sc = decl_scale.get(name)
            if sc is not None:
                L[f"scale__{name}"] = sc
    st = spec["scale_table"]
    binmap = {"encoder3_downscale_conv_w": 28, "bottleneck_rb0_spatial_w": 31, "bottleneck_rb0_pw_expand_w": 32,
              "bottleneck_rb0_pw_contract_w": 34, "bottleneck_rb1_spatial_w": 37, "bottleneck_rb1_pw_expand_w": 38,
              "bottleneck_rb1_pw_contract_w": 40, "bottleneck_rb2_spatial_w": 43, "bottleneck_rb2_pw_expand_w": 44,
              "bottleneck_rb2_pw_contract_w": 46, "bottleneck_upscale_convT_w": 48}
    for k, i in binmap.items():
        L[f"scale__{k}"] = st[i]
    # friendly aliases -> npz keys
    def emb(mod, part): return f"embedded__{mod}_{part}{Q}"
    def bias(mod, part): return f"bias__embedded_{mod}_{part}_bias"
    def reg(mod, part, wkey=None, bkey=None):
        return dict(w=wkey or emb(mod, part), b=bkey or bias(mod, part))
    A = {}
    cnb_mods = [("encoder2_ResidualBlock_0_body", "encoder2_RB0"), ("encoder2_ResidualBlock_1_body", "encoder2_RB1"),
                ("decoder2_ResidualBlock_1_body", "decoder2_RB1"), ("decoder2_ResidualBlock_2_body", "decoder2_ResidualBlock_2")]
    for mod, short in cnb_mods:
        A[f"{short}_conv_dw_weight"] = emb(mod, "conv_dw_weight")
        A[f"{short}_conv_dw_bias"] = bias(mod, "conv_dw")
        A[f"scale__{short}_conv_dw"] = decl_scale[emb(mod, "conv_dw_weight")]
        for p in ["pw_expand", "pw_contract"]:
            A[f"{short}_{p}_weight"] = emb(mod, "conv_" + p + "_weight"); A[f"{short}_{p}_bias"] = bias(mod, "conv_" + p)
            A[f"scale__{short}_{p}"] = decl_scale[emb(mod, "conv_" + p + "_weight")]
    # FNB blocks: enc3 RB0/RB1, dec3 RB1/RB2 (embedded); bottleneck RB0/1/2 (bin); decoder2 RB2 (pass13)
    fnb_mods = {
        "encoder3_ResidualBlock_0": ("embedded__encoder3_ResidualBlock_0_body_spatial_mixing_partial_conv", "encoder3_ResidualBlock_0_body"),
        "encoder3_ResidualBlock_1": ("embedded__encoder3_ResidualBlock_1_body_spatial_mixing_partial_conv", "encoder3_ResidualBlock_1_body"),
        "bottleneck_ResidualBlock_0": ("bottleneck_rb0", "bottleneck_ResidualBlock_0_body"),
        "bottleneck_ResidualBlock_1": ("bottleneck_rb1", "bottleneck_ResidualBlock_1_body"),
        "bottleneck_ResidualBlock_2": ("bottleneck_rb2", "bottleneck_ResidualBlock_2_body"),
        "decoder3_ResidualBlock_1": ("embedded__decoder3_ResidualBlock_1_body_spatial_mixing_partial_conv", "decoder3_ResidualBlock_1_body"),
        "decoder3_ResidualBlock_2": ("embedded__decoder3_ResidualBlock_2_body_spatial_mixing_partial_conv", "decoder3_ResidualBlock_2_body"),
    }
    for mod, (spatial_key, biasmod) in fnb_mods.items():
        if spatial_key.startswith("bottleneck_rb"):
            A[f"{mod}_spatial_weight"] = spatial_key + "_spatial_w"
            A[f"scale__{mod}_spatial"] = L[f"scale__{spatial_key}_spatial_w"]
            A[f"{mod}_pw_expand_weight"] = spatial_key + "_pw_expand_w"
            A[f"scale__{mod}_pw_expand"] = L[f"scale__{spatial_key}_pw_expand_w"]
            A[f"{mod}_pw_contract_weight"] = spatial_key + "_pw_contract_w"
            A[f"scale__{mod}_pw_contract"] = L[f"scale__{spatial_key}_pw_contract_w"]
        else:
            A[f"{mod}_spatial_weight"] = spatial_key + "_weight" + Q
            A[f"scale__{mod}_spatial"] = decl_scale[spatial_key + "_weight" + Q]
            A[f"{mod}_pw_expand_weight"] = emb(biasmod, "pw_expand_weight")
            A[f"scale__{mod}_pw_expand"] = decl_scale[emb(biasmod, "pw_expand_weight")]
            A[f"{mod}_pw_contract_weight"] = emb(biasmod, "pw_contract_weight")
            A[f"scale__{mod}_pw_contract"] = decl_scale[emb(biasmod, "pw_contract_weight")]
        for p, sfx in [("spatial", "spatial_mixing_partial_conv"), ("pw_expand", "pw_expand"), ("pw_contract", "pw_contract")]:
            bk = f"bias__embedded_{biasmod}_{sfx}_bias"
            assert bk in L, bk
            A[f"{mod}_{p}_bias"] = bk
    # downscale convs
    A["enc2_ds_weight"] = emb("encoder2_DownscaleStridedConv2x2", "downscale_conv_weight")
    A["enc2_ds_bias"] = bias("encoder2_DownscaleStridedConv2x2", "downscale_conv")
    A["scale__enc2_ds"] = decl_scale[A["enc2_ds_weight"]]
    A["enc3_ds_weight"] = "encoder3_downscale_conv_w"
    A["enc3_ds_bias"] = "bias__embedded_encoder3_DownscaleStridedConv2x2_downscale_conv_bias"
    A["scale__enc3_ds"] = st[28]
    # CT2D weights (HWCN, OIHW=cin,cout,ky,kx)
    A["bottleneck_ct_weight"] = "bottleneck_upscale_convT_w"; A["scale__bottleneck_ct"] = st[48]
    A["bottleneck_ct_bias"] = "bias__embedded_bottleneck_UpscaleConvTranspose2x2_upscale_conv_bias"
    A["dec3_ct_weight"] = "embedded_hwcn__decoder3_UpscaleConvTranspose2x2_upscale_conv_weight" + Q
    A["scale__dec3_ct"] = decl_scale[A["dec3_ct_weight"]]
    A["dec3_ct_bias"] = "bias__embedded_decoder3_UpscaleConvTranspose2x2_upscale_conv_bias"
    A["dec2_ct_weight"] = "embedded_hwcn__decoder2_UpscaleConvTranspose2x2_upscale_conv_weight" + Q
    A["scale__dec2_ct"] = decl_scale[A["dec2_ct_weight"]]
    A["dec2_ct_bias"] = "bias__embedded_decoder2_UpscaleConvTranspose2x2_upscale_conv_bias"
    L.update(A)
    # resolve string aliases -> arrays (scales stay float)
    for k, v in list(A.items()):
        if isinstance(v, str) and not k.startswith("scale__") and v in L and not isinstance(L[v], str):
            L[k] = L[v]
    L["_calls"] = spec["calls"]
    return L

# pass-0 (feature conv, fp16 weights, fp32 acc). features fp16 [H, W, 8] (ch7=0), W0 [f,ky,kx,c] fp16
def pass0(features_f16, L):
    """out[h,w,f] = clamp(round(((t00+t10)+(t01+t11) + bias) / s)); t_kyx = sum_c w[f,ky,kx,c]*feat[2h+ky,2w+kx,c]
    fp16 inputs/weights, fp32 accumulation (sequential tap order; shader groups (t00+t10)+(t01+t11) — ULP-level difference only)."""
    w0 = L["pass0_weight_fkyxc"].astype(F16)  # [16,2,2,8]
    b = L["pass0_bias"].astype(F32)
    H, W, _ = features_f16.shape
    xf = features_f16.astype(F32)
    acc = np.zeros((H//2, W//2, 16), dtype=F32)
    for ky in range(2):
        for kx in range(2):
            # exact fp16*fp16 products accumulated in fp32 (matches dot2add)
            t = np.einsum("hwc,fc->hwf", xf[ky::2, kx::2,:], w0[:, ky, kx,:].astype(F32))
            acc += t  # sequential tap accumulation (t00+t10)+(t01+t11) tolerance: ULP-level
    s = F32(L["_pass0_scale"])
    q = clamp_s8(round_half_away((acc + b) * (F32(1.0) / s)))
    return {"q": q, "s": float(L["_pass0_scale"])}

# ---------------------------------------------------------------- full graph
def run_graph(x_in, L=None, trace=None):
    """x_in: {"q": int8[H,W,16], "s": s_in}. Returns (output fp16 [H*2? no: [H,W,8] @ upscale res], stats)."""
    if L is None:
        L = load_layers()
    calls = L["_calls"]
    c = {i: calls[i]["args"] for i in range(len(calls))}
    # passes 1..12 + post (index 12)
    x = x_in
    outs = {}
    # pass1/2: ConvNextBlock (args: rcpr0, s_mid1, rcpr1, s_mid2)
    x = convnext(x, L, c[0][0], c[0][1], c[0][2], c[0][3], 0.01933070458471775, "encoder2_RB0")
    outs["p1"] = x
    x = convnext(x, L, c[1][0], c[1][1], c[1][2], c[1][3], 0.02335178479552269, "encoder2_RB1")
    outs["p2"] = x
    # pass3: k2s2b enc2->enc3 (args: q0,q1)
    x = k2s2b(x, L, "enc2_ds_weight", "enc2_ds_bias", L["scale__enc2_ds"], c[2][0], c[2][1]); outs["p3"] = x
    # pass4/5: FNB<32,1> (args: q0,q1,act,o0,o1)
    x = fasternet(x, L, "encoder3_ResidualBlock_0", *c[3][:5], "32"); outs["p4"] = x
