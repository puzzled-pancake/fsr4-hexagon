"""Bit-faithful NumPy reference simulator of the FSR4 INT8 conv graph (passes 0-13, quality preset).

Mirrors the autogenerated HLSL exactly:
  - int32 dot-product accumulation (dot4add_i8packed)
  - fp32 dequant with the SAME multiply order as each shader call site
  - fp16 biases (stored fp16, added in fp32)
  - round() = half away from zero; pack_clamp_s8 = saturate [-128,127]; ReLU applied post-quant = clamp(q,0,127)
  - grouped tensors: channel halves [0,C/2)/[C/2,C) at two scales
  - pass13 CT2D output: fp16(acc*scale) + fp16 bias, added in fp16
Tensors are NHWC numpy arrays: {"q": int8 [H,W,C], "s": float} or {"q": int8, "s0": float, "s1": float}.
"""
import json
from pathlib import Path
import numpy as np

ART = Path(__file__).resolve().parents[1] / "artifacts"
F32 = np.float32
F16 = np.float16

def f32(x): return np.asarray(x, dtype=F32)

def round_half_away(x):
    return (np.sign(x) * np.floor(np.abs(x) + F32(0.5))).astype(np.int64)

def clamp_s8(q):  return np.clip(q, -128, 127).astype(np.int8)
def relu_s8(q):   return np.clip(q, 0, 127).astype(np.int8)

# ---------------------------------------------------------------- int8 conv cores
def conv2d_i8(x_q, w, stride=1, pad=0, groups=1):
    """x_q int8 [H,W,C]; w int8 [Cout, Cin//groups, kh, kw] (OIHW). Returns int64 [H',W',Cout]."""
    H, W, C = x_q.shape
    Cout, Cg, kh, kw = w.shape
    assert Cg * groups == C
    xp = np.zeros((H + 2*pad, W + 2*pad, C), dtype=np.int32)
    xp[pad:pad+H, pad:pad+W] = x_q
    xi = xp.astype(np.int32)
    Ho = (H + 2*pad - kh)//stride + 1
    Wo = (W + 2*pad - kw)//stride + 1
    acc = None
    for ky in range(kh):
        for kx in range(kw):
            patch = xi[ky:ky+stride*Ho:stride, kx:kx+stride*Wo:stride,:] # [Ho,Wo,C]
            wsl = w[:,:, ky, kx].astype(np.int32) # [Cout,C]
            if groups == 1:
                m = (patch.reshape(-1, C) @ wsl.T).reshape(patch.shape[0], patch.shape[1], -1)
            elif groups == Cout:  # depthwise
                m = patch * wsl[:, 0][None, None,:]
            else:                 # grouped: block matmul per group
                m = np.empty((patch.shape[0], patch.shape[1], Cout), dtype=np.int64)
                cg = C // groups
                for g in range(groups):
                    m[:,:, g*cg:(g+1)*cg] = patch[:,:, g*cg:(g+1)*cg] @ wsl[g*cg:(g+1)*cg,:].T
            acc = m if acc is None else acc + m
    return acc.astype(np.int64)

def convtranspose2x2_i8(x_q, w):
    """CT2D k=2 s=2: out[2y+j, 2x+i, o] = sum_c w[c, o, j, i]*x[y, x, c]. w int8 [Cin, Cout, 2, 2]."""
    H, W, C = x_q.shape
    Cout = w.shape[1]
    out = np.zeros((2*H, 2*W, Cout), dtype=np.int64)
    xi = x_q.astype(np.int32)
    for j in range(2):
        for i in range(2):
            m = xi.reshape(-1, C) @ w[:,:, j, i].astype(np.int32) # w[cin, cout]
            out[j::2, i::2,:] = m.reshape(H, W, Cout)
    return out

# ---------------------------------------------------------------- tensor helpers
def dq(t, half=None):
    """dequantize full tensor (grouped-aware) -> f32"""
    if "s" in t:
        return t["q"].astype(F32) * F32(t["s"])
    s0, s1 = F32(t["s0"]), F32(t["s1"])
    C = t["q"].shape[2]
    out = np.empty(t["q"].shape, F32)
    out[:,:,:C//2] = t["q"][:,:,:C//2].astype(F32) * s0
    out[:,:, C//2:] = t["q"][:,:, C//2:].astype(F32) * s1
    return out

# ---------------------------------------------------------------- blocks
def convnext(x, L, rcpr0, s_mid1, rcpr1, s_mid2, s_out, prefix, sim=None):
    """ConvNextBlock: dw3x3 pad1 -> pw C->2C (+ReLU-after-quant) -> pw 2C->C -> skip add -> requant."""
    W0, b0 = L[f"{prefix}_conv_dw_weight"], L[f"{prefix}_conv_dw_bias"]
    W1, b1 = L[f"{prefix}_pw_expand_weight"], L[f"{prefix}_pw_expand_bias"]
    W2, b2 = L[f"{prefix}_pw_contract_weight"], L[f"{prefix}_pw_contract_bias"]
    sw0, sw1, sw2 = F32(L[f"scale__{prefix}_conv_dw"]), F32(L[f"scale__{prefix}_pw_expand"]), F32(L[f"scale__{prefix}_pw_contract"])
    xs = F32(x["s"])
    acc = conv2d_i8(x["q"], W0, stride=1, pad=1, groups=1)  # "conv_dw" is a full conv here (16->16)
    inputscale = xs * sw0
    q = clamp_s8(round_half_away((acc.astype(F32) * inputscale + b0) * F32(rcpr0)))
    acc = conv2d_i8(q, W1)
    inputscale = F32(s_mid1) * sw1
    q = relu_s8(clamp_s8(round_half_away((acc.astype(F32) * inputscale + b1) * F32(rcpr1))))
    acc = conv2d_i8(q, W2)
    inputscale = sw2 * F32(s_mid2)
    result = acc.astype(F32) * inputscale + b2
    result = result + x["q"].astype(F32) * xs
    q = clamp_s8(round_half_away(result * (F32(1.0) / F32(s_out))))
    return {"q": q, "s": s_out}

def k2s2b(x, L, wkey, bkey, s_w, q0, q1):
    """FusedConv2D_k2s2b: 2x2 stride 2 no pad, fp16 bias, grouped 2-scale output."""
    W, b = L[wkey], L[bkey]
    acc = conv2d_i8(x["q"], W, stride=2, pad=0)
    N = acc.shape[2]
    xs, sws = F32(x["s"]), F32(s_w)
    v = acc.astype(F32)
    # HLSL: round((acc * weights.scale * input.scale + bias) * (1.0/qf))
    r = round_half_away((v * sws * xs + b) * (F32(1.0) / F32(q0)))
    q = np.empty(acc.shape, np.int8)
    q[:,:,:N//2] = clamp_s8(r[:,:,:N//2])
    r = round_half_away((v * sws * xs + b) * (F32(1.0) / F32(q1)))
    q[:,:, N//2:] = clamp_s8(r[:,:, N//2:])
    return {"q": q, "s0": q0, "s1": q1}

def _fnb_core(xg, L, prefix, q0, q1, act, variant, order="fnb"):
    """Shared FasterNetBlock internals. Returns (fnb_f32_result[C], concat_scale) pre-skip."""
    W0, b0 = L[f"{prefix}_spatial_weight"], L[f"{prefix}_spatial_bias"]
    W1, b1 = L[f"{prefix}_pw_expand_weight"], L[f"{prefix}_pw_expand_bias"]
    W2, b2 = L[f"{prefix}_pw_contract_weight"], L[f"{prefix}_pw_contract_bias"]
    sw0, sw1, sw2 = F32(L[f"scale__{prefix}_spatial"]), F32(L[f"scale__{prefix}_pw_expand"]), F32(L[f"scale__{prefix}_pw_contract"])
    xq = xg["q"]; C = xq.shape[2]
    groups = 2 if variant == "64" else 1           # 64: grouped partial conv (2x16); 32: single 16ch
    acc = conv2d_i8(xq[:,:,:C//2], W0, stride=1, pad=1, groups=groups)
    if variant == "32" or order == "ct2d":  # acc * (q0 * sw0)  [FNB_CT2D_ADD groups parenthesized for both variants]
        pre = acc.astype(F32) * (F32(q0) * sw0) + b0
    else:                 # acc * q0 * sw0  [FasterNetBlock <64,2>]
        pre = acc.astype(F32) * F32(q0) * sw0 + b0
    q_conv = clamp_s8(round_half_away(pre * (F32(1.0) / F32(q1))))
    # concat (uniform at q1): conv half + passthrough half (passthrough requant at same scale is identity)
    concat = np.concatenate([q_conv, xq[:,:, C//2:]], axis=2)
    acc = conv2d_i8(concat, W1)
    if order == "ct2d":   # vs * (quantScale1 * w1.scale)  [FNB_CT2D_ADD groups parenthesized]
        pre = acc.astype(F32) * (F32(q1) * sw1) + b1
    else:                 # vs * quantScale1 * w1.scale  (left-to-right, both FasterNetBlock variants)
        pre = acc.astype(F32) * F32(q1) * sw1 + b1
    q_relu = relu_s8(clamp_s8(round_half_away(pre * (F32(1.0) / F32(act)))))
    acc = conv2d_i8(q_relu, W2)
    if variant == "32" and order == "fnb":  # vs * sw2 * act  [FasterNetBlock <32,1> left-to-right]
        result = acc.astype(F32) * sw2 * F32(act) + b2
    else:                 # vs * (sw2 * act)  [precomputed weightReluScale in <64,2> and FNB_CT2D_ADD]
        result = acc.astype(F32) * (sw2 * F32(act)) + b2
    return result, xq, C

def fasternet(xg, L, prefix, q0, q1, act, o0, o1, variant):
    result, xq, C = _fnb_core(xg, L, prefix, q0, q1, act, variant)
    out = np.empty(result.shape, np.int8)
    r0 = result[:,:,:C//2] + xq[:,:,:C//2].astype(F32) * F32(q0)
    out[:,:,:C//2] = clamp_s8(round_half_away(r0 * (F32(1.0) / F32(o0))))
    r1 = result[:,:, C//2:] + xq[:,:, C//2:].astype(F32) * F32(q1)
    out[:,:, C//2:] = clamp_s8(round_half_away(r1 * (F32(1.0) / F32(o1))))
    return {"q": out, "s0": o0, "s1": o1}

def fasternet_uniform(xg, L, prefix, q0, q1, act, s_out, variant):
    result, xq, C = _fnb_core(xg, L, prefix, q0, q1, act, variant)
    result[:,:,:C//2] += xq[:,:,:C//2].astype(F32) * F32(q0)
    result[:,:, C//2:] += xq[:,:, C//2:].astype(F32) * F32(q1)
    q = clamp_s8(round_half_away(result * (F32(1.0) / F32(s_out))))
    return {"q": q, "s": s_out}

def fnb_ct2d_add(xg, L, prefix, skip, q0, q1, act, s_fnb, o0, o1, variant, wct_key, bct_key, sct_key):
    """FNB (uniform output scale) + ConvTranspose 2x2 + skip Add at 2x res; grouped output."""
    result, xq, C = _fnb_core(xg, L, prefix, q0, q1, act, variant, order="ct2d")
    result[:,:,:C//2] += xq[:,:,:C//2].astype(F32) * F32(q0)
    result[:,:, C//2:] += xq[:,:, C//2:].astype(F32) * F32(q1)
    fnb_q = clamp_s8(round_half_away(result * (F32(1.0) / F32(s_fnb))))
    Wct, bct = L[wct_key], L[bct_key]
    acc = convtranspose2x2_i8(fnb_q, Wct)
    ct_scale = F32(s_fnb) * F32(L[f"scale__{sct_key}"])
    v = acc.astype(F32) * ct_scale + bct
    sk = skip["q"].astype(F32) * F32(skip["s"])
    v = v + sk
    N = v.shape[2]
    q = np.empty(v.shape, np.int8)
    q[:,:,:N//2] = clamp_s8(round_half_away(v[:,:,:N//2] * (F32(1.0) / F32(o0))))
    q[:,:, N//2:] = clamp_s8(round_half_away(v[:,:, N//2:] * (F32(1.0) / F32(o1))))
    return {"q": q, "s0": o0, "s1": o1}

def fnb_ct2d_add_uniform(xg, L, prefix, skip, q0, q1, act, s_fnb, s_out, variant, wct_key, bct_key, sct_key):
    result, xq, C = _fnb_core(xg, L, prefix, q0, q1, act, variant, order="ct2d")
    result[:,:,:C//2] += xq[:,:,:C//2].astype(F32) * F32(q0)
    result[:,:, C//2:] += xq[:,:, C//2:].astype(F32) * F32(q1)
    fnb_q = clamp_s8(round_half_away(result * (F32(1.0) / F32(s_fnb))))
    Wct, bct = L[wct_key], L[bct_key]
    acc = convtranspose2x2_i8(fnb_q, Wct)
    ct_scale = F32(s_fnb) * F32(L[f"scale__{sct_key}"])
    v = acc.astype(F32) * ct_scale + bct + skip["q"].astype(F32) * F32(skip["s"])
    return {"q": clamp_s8(round_half_away(v * (F32(1.0) / F32(s_out)))), "s": s_out}

def pass13_cnb_ct2d(x, L, prefix, rcpr0, s_mid1, rcpr1, s_mid2, s_cnb, wct_key, bct_key, sct_key):
    """Final CNB (uniform out) + CT2D 16->8, output fp16 (8ch): fp16(acc*scale)+fp16 bias (fp16 add)."""
    cnb = convnext(x, L, rcpr0, s_mid1, rcpr1, s_mid2, s_cnb, prefix)
    Wct, bct = L[wct_key], L[bct_key]
    acc = convtranspose2x2_i8(cnb["q"], Wct)
    ct_scale = F32(s_cnb) * F32(L[f"scale__{sct_key}"])
    h = (acc.astype(F32) * ct_scale).astype(F16)
    return (h + bct.astype(F16)).astype(F16)   # [2H, 2W, 8] fp16

